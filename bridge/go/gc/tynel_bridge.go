//go:build tynelgc

// 本文件属于 gc 包：它通过 overlay 接入 Go 编译器源码树，不新建包，也不修改
// 已准备的 SDK 副本。
//
// 它在 Go 编译器内部把 NIR 构造成高层 IR 节点。
//
// 它只在环境变量 TYNEL_NIR 指向一份 NIR 文件、且当前编译目标是 main 包时生效。
// 用户算法不落成 Go 源码：函数签名、参数、算术、调用和返回都由这里直接建成
// ir.Func，随后交给编译器原有的 typecheck、walk、SSA 和链接流程。
//
// 这里只读取 NIR 的必要字段。格式与语义校验由仓库里的 compiler/nir 完成，
// 编译器内部不重复实现一套完整校验；传进来的内容不合法时直接报错退出。
package gc

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"strconv"
	"strings"

	"cmd/compile/internal/base"
	"cmd/compile/internal/ir"
	"cmd/compile/internal/typecheck"
	"cmd/compile/internal/types"
	"cmd/internal/src"
	"go/constant"
)

// 固定支持文件提供的函数名。
const (
	supportPrintFloat = "tynelPrintFloat64"
	supportPrintBool  = "tynelPrintBool"
	supportBits       = "tynelNumberFromBits"
)

var binaryOps = map[string]ir.Op{
	"+": ir.OADD,
	"-": ir.OSUB,
	"*": ir.OMUL,
	"/": ir.ODIV,
}

// Inject 在包加载完成后把 NIR 中的函数加入编译目标。没有设置 TYNEL_NIR 或
// 当前不是 main 包时什么也不做，普通构建因此不受影响。
func tynelInject(target *ir.Package) {
	path := os.Getenv("TYNEL_NIR")
	if path == "" {
		return
	}
	if debug := os.Getenv("TYNEL_DEBUG"); debug != "" {
		fmt.Fprintf(os.Stderr, "tynel bridge: pkgpath=%q pkgname=%q nir=%q\n", base.Ctxt.Pkgpath, types.LocalPkg.Name, path)
	}
	if types.LocalPkg.Name != "main" {
		return
	}
	if err := inject(target, path); err != nil {
		// 输入不合法按普通编译错误上报，不用内部故障的措辞。
		base.ErrorfAt(base.AutogeneratedPos, 0, "tynel bridge: %v", err)
		base.ExitIfErrors()
	}
}

func inject(target *ir.Package, path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("读取 NIR %s 失败：%w", path, err)
	}
	var m module
	if err := json.Unmarshal(data, &m); err != nil {
		return fmt.Errorf("解析 NIR %s 失败：%w", path, err)
	}
	if m.SchemaVersion != 1 {
		return fmt.Errorf("NIR schemaVersion 为 %d，只接受 1", m.SchemaVersion)
	}
	if len(m.Functions) == 0 {
		return fmt.Errorf("NIR 没有函数")
	}

	pos := base.AutogeneratedPos

	// 先建全部签名：函数体里的调用可能指向后面才声明的函数。
	funcs := make(map[string]*ir.Func, len(m.Functions))
	for _, f := range m.Functions {
		if _, dup := funcs[f.Name]; dup {
			return fmt.Errorf("NIR 函数 %q 重复", f.Name)
		}
		sym := types.LocalPkg.Lookup(f.Name)
		if sym.Def != nil {
			return fmt.Errorf("NIR 函数 %q 与包内已有声明冲突", f.Name)
		}
		sig, err := signature(f, pos)
		if err != nil {
			return err
		}
		fn := ir.NewFunc(pos, pos, sym, sig)
		fn.DeclareParams(true)
		sym.Def = fn.Nname
		funcs[f.Name] = fn
	}

	helper, _ := types.LocalPkg.Lookup(supportPrintFloat).Def.(*ir.Name)
	if helper == nil {
		return fmt.Errorf("缺少固定支持函数 %s", supportPrintFloat)
	}
	boolHelper, _ := types.LocalPkg.Lookup(supportPrintBool).Def.(*ir.Name)
	if boolHelper == nil {
		return fmt.Errorf("缺少固定支持函数 %s", supportPrintBool)
	}
	bitsHelper, _ := types.LocalPkg.Lookup(supportBits).Def.(*ir.Name)
	if bitsHelper == nil {
		return fmt.Errorf("缺少固定支持函数 %s", supportBits)
	}

	for _, f := range m.Functions {
		if err := buildBody(funcs[f.Name], f, funcs, helper, boolHelper, bitsHelper, pos); err != nil {
			return err
		}
	}

	for _, f := range m.Functions {
		fn := funcs[f.Name]
		ir.WithFunc(fn, func() { typecheck.Stmts(fn.Body) })
		fn.Nname.Defn = fn
		target.Funcs = append(target.Funcs, fn)
	}
	return nil
}

func signature(f function, pos src.XPos) (*types.Type, error) {
	params := make([]*types.Field, 0, len(f.Params))
	for _, p := range f.Params {
		t, err := goType(p.Type)
		if err != nil {
			return nil, fmt.Errorf("函数 %q 的参数 %q：%w", f.Name, p.Name, err)
		}
		params = append(params, types.NewField(pos, nil, t))
	}
	var results []*types.Field
	switch f.Result {
	case "number", "bool":
		t, err := goType(f.Result)
		if err != nil {
			return nil, fmt.Errorf("函数 %q 的返回类型：%w", f.Name, err)
		}
		results = append(results, types.NewField(pos, nil, t))
	case "void":
	default:
		return nil, fmt.Errorf("函数 %q 的返回类型 %q 不支持", f.Name, f.Result)
	}
	return types.NewSignature(nil, params, results), nil
}

// goType 把 NIR 类型映射成 Go 类型。bool 用一字节的 TBOOL，不借 float64 的
// 0 与 1 表示：参数和结果都不做数字真假转换。
func goType(t string) (*types.Type, error) {
	switch t {
	case "number":
		return types.Types[types.TFLOAT64], nil
	case "bool":
		return types.Types[types.TBOOL], nil
	}
	return nil, fmt.Errorf("类型 %q 不支持", t)
}

func buildBody(fn *ir.Func, f function, funcs map[string]*ir.Func, helper, boolHelper, bitsHelper *ir.Name, pos src.XPos) error {
	params := make(map[string]*ir.Name, len(f.Params))
	locals := make(map[string]*ir.Name)
	for i, p := range f.Params {
		if i >= len(fn.Dcl) {
			return fmt.Errorf("函数 %q 的参数数量与声明不符", f.Name)
		}
		params[p.Name] = fn.Dcl[i]
	}

	body := make([]ir.Node, 0, len(f.Body))
	discarded := 0
	for _, s := range f.Body {
		switch s.Op {
		case "return":
			if s.Value == nil {
				body = append(body, ir.NewReturnStmt(pos, nil))
				continue
			}
			v, err := buildExpr(s.Value, params, locals, funcs, bitsHelper, pos)
			if err != nil {
				return err
			}
			body = append(body, ir.NewReturnStmt(pos, []ir.Node{v}))
		case "let":
			if s.Value == nil {
				return fmt.Errorf("let %q 缺少值", s.Name)
			}
			if _, exists := locals[s.Name]; exists {
				return fmt.Errorf("局部值 %q 重复定义", s.Name)
			}
			v, err := buildExpr(s.Value, params, locals, funcs, bitsHelper, pos)
			if err != nil {
				return err
			}
			// 局部值就是一个 Go 自动变量：声明在函数里，赋值一次，之后按名字读。
			// 类型跟着值走，bool 局部值不会被塞进 float64 槽位。
			typ, err := exprGoType(s.Value, params, locals, funcs)
			if err != nil {
				return err
			}
			sym := &types.Sym{Name: s.Name, Pkg: types.LocalPkg}
			local := fn.NewLocal(pos, sym, typ)
			locals[s.Name] = local
			body = append(body, ir.NewAssignStmt(pos, local, v))
		case "discard":
			v, err := buildExpr(s.Value, params, locals, funcs, bitsHelper, pos)
			if err != nil {
				return err
			}
			if isVoidCall(s.Value, funcs) {
				// void 调用本身就是语句形状，直接放进函数体。
				body = append(body, v)
				break
			}
			// 数值或布尔表达式不能裸着当语句：一个光秃秃的变量名会让编译器报
			// "unexpected stmt"。赋给一个从不读取的临时变量，求值照做，
			// 结果丢掉；死存储由 SSA 清掉。
			typ, err := exprGoType(s.Value, params, locals, funcs)
			if err != nil {
				return err
			}
			discarded++
			sym := &types.Sym{Name: fmt.Sprintf("_tynel_discard_%d", discarded), Pkg: types.LocalPkg}
			tmp := fn.NewLocal(pos, sym, typ)
			body = append(body, ir.NewAssignStmt(pos, tmp, v))
		case "print":
			v, err := buildExpr(s.Value, params, locals, funcs, bitsHelper, pos)
			if err != nil {
				return err
			}
			// print 不生成 Go 源码，而是调用固定支持函数；number 与 bool 各有
			// 一个目标，选择依据是值的类型，不是运行时的判断。
			typ, err := exprGoType(s.Value, params, locals, funcs)
			if err != nil {
				return err
			}
			target := helper
			if typ == types.Types[types.TBOOL] {
				target = boolHelper
			}
			body = append(body, ir.NewCallExpr(pos, ir.OCALL, target, []ir.Node{v}))
		default:
			return fmt.Errorf("不支持的语句 op %q", s.Op)
		}
	}
	// 编译器把「没有函数体」当成外部声明：gc.compile 里 len(fn.Body)==0 时只
	// 生成声明、不生成代码。void 函数正常结束等价于一条空 return，补上它，
	// 空入口才会成为可执行函数。
	if len(body) == 0 {
		if f.Result != "void" {
			return fmt.Errorf("函数 %q 返回 %s，但函数体为空", f.Name, f.Result)
		}
		body = append(body, ir.NewReturnStmt(pos, nil))
	}
	fn.Body = body
	return nil
}

func buildExpr(e *expr, params, locals map[string]*ir.Name, funcs map[string]*ir.Func, bitsHelper *ir.Name, pos src.XPos) (ir.Node, error) {
	if e == nil {
		return nil, fmt.Errorf("表达式为空")
	}
	switch e.Op {
	case "number":
		bits, err := parseBits(e.Bits)
		if err != nil {
			return nil, err
		}
		v := math.Float64frombits(bits)
		if needsBits(v) {
			// NaN、无穷和负零没有字面量形式：go/constant 会把负零归一成
			// 正零，也没有 NaN 和无穷的表示。改成调用按位构造的支持函数。
			lit := ir.NewBasicLit(pos, types.Types[types.TUINT64], constant.MakeUint64(bits))
			return ir.NewCallExpr(pos, ir.OCALL, bitsHelper, []ir.Node{lit}), nil
		}
		return ir.NewBasicLit(pos, types.Types[types.TFLOAT64], constant.MakeFloat64(v)), nil
	case "bool":
		if e.Value == nil {
			return nil, fmt.Errorf("bool 缺少 value")
		}
		return ir.NewBasicLit(pos, types.Types[types.TBOOL], constant.MakeBool(*e.Value)), nil
	case "not":
		if e.Operand == nil {
			return nil, fmt.Errorf("not 缺少操作数")
		}
		x, err := buildExpr(e.Operand, params, locals, funcs, bitsHelper, pos)
		if err != nil {
			return nil, err
		}
		return ir.NewUnaryExpr(pos, ir.ONOT, x), nil
	case "param":
		n, ok := params[e.Name]
		if !ok {
			return nil, fmt.Errorf("引用不存在的参数 %q", e.Name)
		}
		return n, nil
	case "local":
		n, ok := locals[e.Name]
		if !ok {
			return nil, fmt.Errorf("引用未定义的局部值 %q", e.Name)
		}
		return n, nil
	case "call":
		callee, ok := funcs[e.Function]
		if !ok {
			return nil, fmt.Errorf("调用不存在的函数 %q", e.Function)
		}
		args := make([]ir.Node, 0, len(e.Args))
		for i := range e.Args {
			a, err := buildExpr(&e.Args[i], params, locals, funcs, bitsHelper, pos)
			if err != nil {
				return nil, err
			}
			args = append(args, a)
		}
		return ir.NewCallExpr(pos, ir.OCALL, callee.Nname, args), nil
	case "binary":
		op, ok := binaryOps[e.Operator]
		if !ok {
			return nil, fmt.Errorf("不支持的运算符 %q", e.Operator)
		}
		x, err := buildExpr(e.Left, params, locals, funcs, bitsHelper, pos)
		if err != nil {
			return nil, err
		}
		y, err := buildExpr(e.Right, params, locals, funcs, bitsHelper, pos)
		if err != nil {
			return nil, err
		}
		return ir.NewBinaryExpr(pos, op, x, y), nil
	default:
		return nil, fmt.Errorf("不支持的表达式 op %q", e.Op)
	}
}

// exprGoType 返回一个 NIR 表达式在 Go 里的类型。局部值、参数和调用的类型
// 从已建好的声明上取；字面量与运算按操作符判断。它只服务于「分配什么类型的
// 局部变量」「调用哪个打印函数」，不重复验证器的工作。
func exprGoType(e *expr, params, locals map[string]*ir.Name, funcs map[string]*ir.Func) (*types.Type, error) {
	switch e.Op {
	case "number", "binary":
		return types.Types[types.TFLOAT64], nil
	case "bool", "not":
		return types.Types[types.TBOOL], nil
	case "param":
		n, ok := params[e.Name]
		if !ok {
			return nil, fmt.Errorf("引用不存在的参数 %q", e.Name)
		}
		return n.Type(), nil
	case "local":
		n, ok := locals[e.Name]
		if !ok {
			return nil, fmt.Errorf("引用未定义的局部值 %q", e.Name)
		}
		return n.Type(), nil
	case "call":
		callee, ok := funcs[e.Function]
		if !ok {
			return nil, fmt.Errorf("调用不存在的函数 %q", e.Function)
		}
		results := callee.Type().Results()
		if len(results) != 1 {
			return nil, fmt.Errorf("函数 %q 没有返回值，不能作为值使用", e.Function)
		}
		return results[0].Type, nil
	}
	return nil, fmt.Errorf("无法确定表达式 op %q 的类型", e.Op)
}

// isVoidCall 报告一个 NIR 表达式是不是对 void 函数的直接调用。只有它可以直接
// 作为语句；其他表达式需要一个承接结果的位置。
func isVoidCall(e *expr, funcs map[string]*ir.Func) bool {
	if e == nil || e.Op != "call" {
		return false
	}
	callee, ok := funcs[e.Function]
	if !ok {
		return false
	}
	return len(callee.Type().Results()) == 0
}

// needsBits 报告一个值是否必须按位构造：负零、NaN 和正负无穷。
func needsBits(v float64) bool {
	return math.IsNaN(v) || math.IsInf(v, 0) || (v == 0 && math.Signbit(v))
}

func parseBits(bits string) (uint64, error) {
	s := strings.TrimSpace(bits)
	s = strings.TrimPrefix(strings.TrimPrefix(s, "0x"), "0X")
	if len(s) != 16 {
		return 0, fmt.Errorf("bits %q 必须是 16 位十六进制", bits)
	}
	v, err := strconv.ParseUint(s, 16, 64)
	if err != nil {
		return 0, fmt.Errorf("bits %q 不是合法的十六进制：%w", bits, err)
	}
	return v, nil
}

// NIR 文件的必要字段。完整结构与校验在 compiler/nir，这里只读 bridge 用得上的部分。
type module struct {
	SchemaVersion int        `json:"schemaVersion"`
	Entry         string     `json:"entry"`
	Functions     []function `json:"functions"`
}

type function struct {
	Name   string  `json:"name"`
	Params []param `json:"params"`
	Result string  `json:"result"`
	Body   []stmt  `json:"body"`
}

type param struct {
	Name string `json:"name"`
	Type string `json:"type"`
}

type stmt struct {
	Op    string `json:"op"`
	Name  string `json:"name,omitempty"`
	Value *expr  `json:"value"`
}

type expr struct {
	Op       string `json:"op"`
	Bits     string `json:"bits"`
	Value    *bool  `json:"value"`
	Name     string `json:"name"`
	Function string `json:"function"`
	Args     []expr `json:"args"`
	Operator string `json:"operator"`
	Left     *expr  `json:"left"`
	Right    *expr  `json:"right"`
	Operand  *expr  `json:"operand"`
}
